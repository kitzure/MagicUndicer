"""Desktop layout and styles for the atlas reconstruction workflow."""

import tkinter as tk
from tkinter import ttk

BG = "#eef2f1"
TEXT = "#1e302b"
MUTED = "#596c65"
ACCENT = "#176554"


def styles(root):
    s = ttk.Style(root)
    s.theme_use("clam")
    s.configure(".", font=("Segoe UI", 11), background=BG, foreground=TEXT)
    s.configure("TFrame", background=BG)
    s.configure("TLabel", background=BG)
    s.configure("Panel.TFrame", background="white")
    s.configure("Panel.TLabel", background="white")
    s.configure("Heading.TLabel", background="white", font=("Segoe UI", 12, "bold"))
    s.configure("Title.TLabel", font=("Segoe UI", 23, "bold"))
    s.configure("Muted.TLabel", foreground=MUTED)
    s.configure("Hint.TLabel", background="white", foreground=MUTED)
    s.configure("Warning.TLabel", background="white", foreground="#a52a2a")
    s.configure("Good.TLabel", background="white", foreground=ACCENT)
    s.configure("TButton", padding=(12, 8), background="#f2f6f4", bordercolor="#c9d5cf")
    s.map("TButton", background=[("active", "#e3ebe6")], foreground=[("disabled", "#7c8982")])
    s.configure("Primary.TButton", background=ACCENT, foreground="white", font=("Segoe UI", 12, "bold"), padding=(14, 10))
    s.map("Primary.TButton", background=[("disabled", "#d5ded9"), ("active", "#0d5041")], foreground=[("disabled", "#6a7f72"), ("!disabled", "white")])
    s.configure("Link.TButton", borderwidth=0, background="white", foreground=ACCENT, padding=(0, 5))
    s.map("Link.TButton", background=[("active", "#f3f7f5")])
    s.configure("TEntry", fieldbackground="white", padding=7)
    s.configure("Treeview", background="white", fieldbackground="white", rowheight=29, borderwidth=0)
    s.map("Treeview", background=[("selected", "#dceee5")], foreground=[("selected", TEXT)])
    s.configure("Treeview.Heading", background="#f1f5f3", font=("Segoe UI", 10, "bold"), padding=(6, 5))
    s.configure("TCheckbutton", background="white", padding=(0, 4))
    s.configure("Horizontal.TProgressbar", background=ACCENT, troughcolor="#d8e2dc", thickness=7)
    s.configure("Error.Horizontal.TProgressbar", background="#a52a2a", troughcolor="#f0dddd")
    s.configure("TNotebook", background="white", borderwidth=0)
    s.configure("TNotebook.Tab", padding=(12, 7))


def build(app):
    root = app.root
    main = ttk.Frame(root, padding=20)
    main.pack(fill="both", expand=True)
    main.columnconfigure(0, weight=1)
    main.rowconfigure(1, weight=1)
    header = ttk.Frame(main)
    header.grid(row=0, column=0, sticky="ew", pady=(0, 18))
    ttk.Label(header, text="MagicUndicer", style="Title.TLabel").pack(anchor="w")
    ttk.Label(header, text="Rebuild images from a tiled atlas and its MonoBehaviour metadata.", style="Muted.TLabel").pack(anchor="w", pady=(2, 0))

    workspace = ttk.Frame(main)
    workspace.grid(row=1, column=0, sticky="nsew")
    workspace.columnconfigure(1, weight=1)
    workspace.rowconfigure(0, weight=1)
    left_shell = ttk.Frame(workspace, style="Panel.TFrame", width=365)
    left_shell.grid(row=0, column=0, sticky="ns", padx=(0, 16))
    left_shell.grid_propagate(False)
    left_shell.columnconfigure(0, weight=1)
    left_shell.rowconfigure(0, weight=1)
    app.control_canvas = tk.Canvas(left_shell, background="white", highlightthickness=0, width=345)
    app.control_canvas.grid(row=0, column=0, sticky="nsew")
    control_scroll = ttk.Scrollbar(left_shell, command=app.control_canvas.yview)
    control_scroll.grid(row=0, column=1, sticky="ns")
    app.control_canvas.configure(yscrollcommand=control_scroll.set)
    left = ttk.Frame(app.control_canvas, style="Panel.TFrame", padding=16)
    inner = app.control_canvas.create_window(0, 0, window=left, anchor="nw")
    left.bind("<Configure>", lambda _: app.control_canvas.configure(scrollregion=app.control_canvas.bbox("all")))
    app.control_canvas.bind("<Configure>", lambda e: app.control_canvas.itemconfigure(inner, width=e.width))
    left.columnconfigure(0, weight=1)

    ttk.Label(left, text="1  Add your files", style="Heading.TLabel").grid(row=0, column=0, sticky="w")
    ttk.Label(left, text="Both the atlas and its matching JSON are needed.", style="Hint.TLabel", wraplength=325).grid(row=1, column=0, sticky="w", pady=(4, 12))
    pickers = ttk.Frame(left, style="Panel.TFrame")
    pickers.grid(row=2, column=0, sticky="ew")
    pickers.columnconfigure(0, weight=1)
    pickers.columnconfigure(1, weight=1)
    app.button(pickers, "Add atlas…", app.add_images).grid(row=0, column=0, sticky="ew", padx=(0, 7))
    app.metadata_button = app.button(pickers, "Add JSON…", app.add_metadata)
    app.metadata_button.grid(row=0, column=1, sticky="ew")
    app.button(pickers, "Import export folder…", app.add_folder).grid(row=1, column=0, columnspan=2, sticky="ew", pady=(7, 0))

    app.drop_hint = ttk.Label(left, text="You can also drop images + JSON here.", style="Hint.TLabel", wraplength=325)
    app.drop_hint.grid(row=3, column=0, sticky="w", pady=(10, 8))
    selected_frame = ttk.Frame(left, style="Panel.TFrame")
    selected_frame.grid(row=4, column=0, sticky="ew")
    selected_frame.columnconfigure(0, weight=1)
    app.inputs = ttk.Treeview(selected_frame, columns=("type", "path"), show="headings", height=2, selectmode="extended")
    app.inputs.heading("type", text="Type")
    app.inputs.heading("path", text="Selected file")
    app.inputs.column("type", width=80, stretch=False)
    app.inputs.column("path", width=218)
    app.inputs.grid(row=0, column=0, sticky="ew")
    scroll = ttk.Scrollbar(selected_frame, orient="vertical", command=app.inputs.yview)
    scroll.grid(row=0, column=1, sticky="ns")
    app.inputs.configure(yscrollcommand=scroll.set)
    app.inputs.bind("<Delete>", lambda _: app.remove_selected())
    app.inputs.bind("<<TreeviewSelect>>", app.preview_input)
    ready = ttk.Frame(left, style="Panel.TFrame")
    ready.grid(row=5, column=0, sticky="new", pady=(7, 12))
    ttk.Label(ready, textvariable=app.queue_label, style="Hint.TLabel", wraplength=325).pack(anchor="w")
    app.readiness_label = ttk.Label(ready, textvariable=app.readiness, style="Hint.TLabel", wraplength=325)
    app.readiness_label.pack(anchor="w", pady=(4, 0))
    remove = app.button(ready, "Remove selected", app.remove_selected)
    remove.configure(style="Link.TButton")
    remove.pack(anchor="w", pady=(3, 0))

    save = ttk.Frame(left_shell, style="Panel.TFrame", padding=(16, 10, 16, 0))
    save.grid(row=1, column=0, columnspan=2, sticky="ew")
    save.columnconfigure(0, weight=1)
    ttk.Label(save, text="2  Choose a save folder", style="Heading.TLabel").grid(row=0, column=0, columnspan=2, sticky="w", pady=(0, 8))
    app.output_entry = ttk.Entry(save, textvariable=app.output)
    app.output_entry.grid(row=1, column=0, sticky="ew")
    app.locked_widgets.append(app.output_entry)
    app.button(save, "Browse…", app.choose_output).grid(row=1, column=1, padx=(7, 0))

    ttk.Label(left, textvariable=app.options_summary, style="Hint.TLabel", wraplength=310).grid(row=8, column=0, sticky="w", pady=(0, 8))
    actions = ttk.Frame(left_shell, style="Panel.TFrame", padding=(16, 12, 16, 16))
    actions.grid(row=2, column=0, columnspan=2, sticky="ew")
    actions.columnconfigure(0, weight=1)
    actions.columnconfigure(1, weight=1)
    actions.columnconfigure(2, weight=1)
    app.start_button = app.button(actions, "Undice images", lambda: app.start(False), primary=True)
    app.start_button.grid(row=0, column=0, columnspan=3, sticky="ew", pady=(0, 8))
    app.button(actions, "Check files", lambda: app.start(True)).grid(row=1, column=0, sticky="ew", padx=(0, 7))
    app.stop_button = app.button(actions, "Stop", app.stop, lock=False)
    app.stop_button.grid(row=1, column=1, sticky="ew")
    app.stop_button.configure(state="disabled")
    app.options_button = app.button(actions, "Options…", app.toggle_options)
    app.options_button.grid(row=1, column=2, sticky="ew", padx=(7, 0))

    right = ttk.Frame(workspace, style="Panel.TFrame", padding=16)
    right.grid(row=0, column=1, sticky="nsew")
    right.columnconfigure(0, weight=1)
    right.rowconfigure(1, weight=3)
    right.rowconfigure(3, weight=2)
    preview_heading = ttk.Label(right, textvariable=app.preview_label, style="Heading.TLabel")
    preview_heading.grid(row=0, column=0, sticky="w", pady=(0, 10))
    app.preview = tk.Canvas(right, background="#f4f7f5", borderwidth=0, highlightthickness=0, height=260)
    app.preview.grid(row=1, column=0, sticky="nsew")
    app.preview.bind("<Configure>", app.redraw_preview)
    app.preview_caption = ttk.Label(right, text="Choose an atlas to preview it. Restored images will appear here after export.", style="Hint.TLabel", wraplength=540)
    app.preview_caption.grid(row=2, column=0, sticky="w", pady=(8, 16))

    app.notebook = ttk.Notebook(right)
    app.notebook.grid(row=3, column=0, sticky="nsew")
    results_frame = ttk.Frame(app.notebook, style="Panel.TFrame")
    log_frame = ttk.Frame(app.notebook, style="Panel.TFrame")
    app.notebook.add(results_frame, text="Restored images")
    app.notebook.add(log_frame, text="Activity log")
    results_frame.columnconfigure(0, weight=1)
    results_frame.rowconfigure(0, weight=1)
    app.results = ttk.Treeview(results_frame, columns=("status", "name"), show="headings", selectmode="browse", height=4)
    app.results.heading("status", text="Result")
    app.results.heading("name", text="Image name")
    app.results.column("status", width=90, stretch=False)
    app.results.column("name", width=360)
    app.results.grid(row=0, column=0, sticky="nsew")
    result_scroll = ttk.Scrollbar(results_frame, command=app.results.yview)
    result_scroll.grid(row=0, column=1, sticky="ns")
    app.results.configure(yscrollcommand=result_scroll.set)
    app.results.bind("<<TreeviewSelect>>", app.preview_result)
    app.results.bind("<Double-1>", app.open_result)
    app.results.bind("<Return>", app.open_result)
    app.detail = ttk.Label(results_frame, text="Select a result to preview it. Double-click to open the PNG.", style="Hint.TLabel", wraplength=540)
    app.detail.grid(row=1, column=0, columnspan=2, sticky="ew", pady=(8, 0))
    log_frame.columnconfigure(0, weight=1)
    log_frame.rowconfigure(0, weight=1)
    app.log = tk.Text(log_frame, font=("Consolas", 10), bg="white", fg=TEXT, state="disabled", wrap="word", relief="flat", padx=10, pady=8, height=4)
    app.log.grid(row=0, column=0, sticky="nsew")
    log_scroll = ttk.Scrollbar(log_frame, command=app.log.yview)
    log_scroll.grid(row=0, column=1, sticky="ns")
    app.log.configure(yscrollcommand=log_scroll.set)
    app.log.tag_configure("error", foreground="#a52a2a")

    footer = ttk.Frame(main)
    footer.grid(row=2, column=0, sticky="ew", pady=(14, 0))
    footer.columnconfigure(0, weight=1)
    app.status_label = ttk.Label(footer, textvariable=app.status, wraplength=780)
    app.status_label.grid(row=0, column=0, columnspan=3, sticky="ew")
    app.progress = ttk.Progressbar(footer, maximum=100)
    app.progress.grid(row=1, column=0, columnspan=3, sticky="ew", pady=(8, 7))
    ttk.Label(footer, textvariable=app.counters, style="Muted.TLabel").grid(row=2, column=0, sticky="w")
    app.report_button = app.button(footer, "Open report", app.open_report, lock=False)
    app.report_button.grid(row=2, column=1, padx=(8, 0))
    app.report_button.configure(state="disabled")
    app.button(footer, "Open output folder", app.open_output, lock=False).grid(row=2, column=2, padx=(8, 0))

    main.bind("<Configure>", lambda e: app.status_label.configure(wraplength=max(100, e.width - 40)))
    right.bind("<Configure>", lambda e: (preview_heading.configure(wraplength=max(100, e.width - 32)),
                                       app.preview_caption.configure(wraplength=max(100, e.width - 32)),
                                       app.detail.configure(wraplength=max(100, e.width - 32))))
    try:
        from tkinterdnd2 import DND_FILES
        for widget in (root, left, app.inputs, app.drop_hint, app.preview):
            widget.drop_target_register(DND_FILES)
            widget.dnd_bind("<<Drop>>", app.drop)
    except (ImportError, AttributeError, tk.TclError):
        app.drop_hint.configure(text="Use the buttons above to add your files.")
    def scroll_controls(event):
        widget = event.widget
        if widget is app.inputs:
            return
        while widget is not None:
            if widget is left_shell:
                app.control_canvas.yview_scroll(-int(event.delta / 120), "units")
                break
            widget = getattr(widget, "master", None)
    root.bind("<MouseWheel>", scroll_controls, add="+")
    app.metadata_button.focus_set()
